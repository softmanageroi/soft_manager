const { test } = require('node:test');
const assert = require('node:assert/strict');
const ExcelJS = require('exceljs');
const { read } = require('../js/stock-import');

function makeFile(name, contents) {
  const buffer = Buffer.isBuffer(contents) ? contents : Buffer.from(contents);
  return {
    name,
    size: buffer.length,
    text: async () => buffer.toString('utf8'),
    arrayBuffer: async () => buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength)
  };
}

test('reads reordered stock headers after title rows and always adds duplicate item rows', async () => {
  const workbook = new ExcelJS.Workbook();
  workbook.addWorksheet('Notes').addRow(['Report']);
  const stock = workbook.addWorksheet('Stock');
  stock.addRow(['Warehouse balance report']);
  stock.addRow(['Balance Quantity', 'Description', 'Item Number', 'Unit']);
  stock.addRow([4, 'Item one', 'ITM1', 'EA']);
  stock.addRow([6, 'Item one', 'ITM1', 'EA']);
  const file = makeFile('stock.xlsx', Buffer.from(await workbook.xlsx.writeBuffer()));

  const result = await read(file, ExcelJS);
  assert.equal(result.mode, 'add');
  assert.equal(result.quantities.get('itm1'), 10);
});

test('reads semicolon-delimited CSV and common SKU/On Hand headers', async () => {
  const file = makeFile(
    'stock.csv',
    'Export generated by inventory system\nOn Hand;SKU;Description\n2.5;SKU-1;Item one\n'
  );
  const result = await read(file, ExcelJS);
  assert.equal(result.mode, 'add');
  assert.equal(result.quantities.get('sku-1'), 2.5);
});

test('accepts item name, punctuated item-code headers, and localized quantity numbers', async () => {
  const file = makeFile(
    'balance.csv',
    'Stock report\nItem Name|Item Code / Number|Balance Qty (Nos.)\nItem one|ITM-1|1.234,50\n'
  );
  const result = await read(file, ExcelJS);
  assert.equal(result.quantities.get('itm-1'), 1234.5);
  assert.equal(result.mode, 'add');
});

test('supports standard thousands separators in quantity cells', async () => {
  const file = makeFile('balance.csv', 'SKU,Quantity\nSKU-1,"1,234.50"\n');
  const result = await read(file, ExcelJS);
  assert.equal(result.quantities.get('sku-1'), 1234.5);
});

test('rejects native Numbers files with a conversion hint', async () => {
  const file = makeFile('stock.xlsx', 'Index/Document.iwa');
  await assert.rejects(read(file, ExcelJS), /Apple Numbers file detected/);
});

test('requires recognizable item-code and quantity headers', async () => {
  const file = makeFile('stock.csv', 'Product;Amount\nItem one;3\n');
  await assert.rejects(read(file, ExcelJS), /Item Code\/Item Number and Quantity\/Stock headers/);
});
