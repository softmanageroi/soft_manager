const { test } = require('node:test');
const assert = require('node:assert/strict');
const ExcelJS = require('exceljs');
const { read, applyToItems, applyCategoriesToItems } = require('../js/stock-import');

function makeFile(name, contents) {
  const buffer = Buffer.isBuffer(contents) ? contents : Buffer.from(contents);
  return {
    name,
    size: buffer.length,
    text: async () => buffer.toString('utf8'),
    arrayBuffer: async () => buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength)
  };
}

test('reads reordered stock headers after title rows and always adds duplicate item rows', async () => {
  const workbook = new ExcelJS.Workbook();
  workbook.addWorksheet('Notes').addRow(['Report']);
  const stock = workbook.addWorksheet('Stock');
  stock.addRow(['Warehouse balance report']);
  stock.addRow(['Balance Quantity', 'Description', 'Item Number', 'Unit']);
  stock.addRow([4, 'Item one', 'ITM1', 'EA']);
  stock.addRow([6, 'Item one', 'ITM1', 'EA']);
  const file = makeFile('stock.xlsx', Buffer.from(await workbook.xlsx.writeBuffer()));

  const result = await read(file, ExcelJS);
  assert.equal(result.mode, 'add');
  assert.equal(result.quantities.get('itm1'), 10);
  assert.equal(result.records.get('itm1').name, 'Item one');
  const applied = applyToItems([{ id: 1, code: 'ITM1', name: 'Existing', stock: 5 }], result);
  assert.equal(applied.items[0].stock, 15);
  assert.equal(applied.createdCount, 0);
  assert.equal(applied.updatedCount, 1);
});

test('reads semicolon-delimited CSV and common SKU/On Hand headers', async () => {
  const file = makeFile(
    'stock.csv',
    'Export generated by inventory system\nOn Hand;SKU;Description\n2.5;SKU-1;Item one\n'
  );
  const result = await read(file, ExcelJS);
  assert.equal(result.mode, 'add');
  assert.equal(result.quantities.get('sku-1'), 2.5);
});

test('accepts item name, punctuated item-code headers, and localized quantity numbers', async () => {
  const file = makeFile(
    'balance.csv',
    'Stock report\nItem Name|Item Code / Number|Balance Quantity (Nos.)\nItem one|ITM-1|1.234,50\n'
  );
  const result = await read(file, ExcelJS);
  assert.equal(result.quantities.get('itm-1'), 1234.5);
  assert.equal(result.mode, 'add');
});

test('creates missing items from item name, code, unit, and quantity', async () => {
  const file = makeFile('items.csv', 'Item Name,Item Code,Unit,Quantity\nNew item,ITM-NEW,Kg,2.5\n');
  const importData = await read(file, ExcelJS);
  const applied = applyToItems([], importData);

  assert.equal(applied.createdCount, 1);
  assert.equal(applied.updatedCount, 0);
  assert.deepEqual(applied.items[0], {
    id: 1,
    createdDate: applied.items[0].createdDate,
    name: 'New item',
    code: 'ITM-NEW',
    type: 'Finished goods',
    category: '',
    brand: '',
    unit: 'Kg',
    stock: 2.5,
    price: 0,
    gst: 18,
    description: ''
  });
});

test('imports department as an item category and can categorize existing items without changing stock', async () => {
  const file = makeFile(
    'departments.csv',
    'Item Name,Item Code,Department,Unit,Quantity\nPump,MEP-1,MEP,Nos,4\n'
  );
  const importData = await read(file, ExcelJS);
  const created = applyToItems([], importData);
  assert.equal(created.items[0].category, 'MEP');

  const existing = applyToItems([
    { id: 1, code: 'MEP-1', name: 'Pump', category: '', stock: 3 }
  ], importData);
  assert.equal(existing.items[0].category, 'MEP');
  assert.equal(existing.items[0].stock, 7);

  const categorized = applyCategoriesToItems([
    { id: 1, code: 'MEP-1', name: 'Pump', category: '', stock: 3 }
  ], importData);
  assert.equal(categorized.items[0].category, 'MEP');
  assert.equal(categorized.items[0].stock, 3);
  assert.equal(categorized.updatedCount, 1);
});

test('rejects repeated item codes assigned to conflicting departments', async () => {
  const file = makeFile(
    'departments.csv',
    'Item Name,Item Code,Department,Quantity\nPump,ITEM-1,MEP,4\nPump,ITEM-1,Civil,2\n'
  );
  await assert.rejects(read(file, ExcelJS), /different departments or categories/);
});

test('rejects a missing item without a name and leaves original items unchanged', async () => {
  const file = makeFile('items.csv', 'Item Code,Quantity\nITM-NEW,2\n');
  const importData = await read(file, ExcelJS);
  const existing = [{ id: 1, code: 'ITM-1', stock: 3 }];

  assert.throws(() => applyToItems(existing, importData), /has no Item Name/);
  assert.equal(existing[0].stock, 3);
});

test('supports standard thousands separators in quantity cells', async () => {
  const file = makeFile('balance.csv', 'SKU,Quantity\nSKU-1,"1,234.50"\n');
  const result = await read(file, ExcelJS);
  assert.equal(result.quantities.get('sku-1'), 1234.5);
});

test('finds headers after titles and handles delimiters inside title rows', async () => {
  const file = makeFile(
    'stock.csv',
    'Stock report, generated today, for warehouse\nItem No.;Qty Units;Description\nITM-2;3;Item, two\nITM-3;4;Item, three\n'
  );
  const result = await read(file, ExcelJS);
  assert.equal(result.quantities.get('itm-2'), 3);
  assert.equal(result.quantities.get('itm-3'), 4);
});

test('rejects native Numbers files with a conversion hint', async () => {
  const file = makeFile('stock.xlsx', 'Index/Document.iwa');
  await assert.rejects(read(file, ExcelJS), /Apple Numbers file detected/);
});

test('requires recognizable item-code and quantity headers', async () => {
  const file = makeFile('stock.csv', 'Product;Amount\nItem one;3\n');
  await assert.rejects(read(file, ExcelJS), /Item Code\/Item Number and Quantity\/Stock headers/);
});
